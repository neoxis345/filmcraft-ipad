#!/bin/bash
# Build FilmCraft for iPadOS and upload it to TestFlight. Needs a paid Apple Developer account and an
# app record with the same bundle identifier in App Store Connect.
#
#   FILMCRAFT_TEAM=ABCDE12345 FILMCRAFT_BUNDLE_ID=org.example.filmcraft packaging/ios/testflight.sh
#
# Uploads with the Apple ID signed in to Xcode, or with an App Store Connect API key when these three
# are set. The key file stays outside the repository; it is never copied or printed:
#   ASC_KEY_PATH=/path/outside/the/repo/AuthKey_XXXX.p8 ASC_KEY_ID=XXXX ASC_ISSUER_ID=xxxxxxxx-…
#
# FILMCRAFT_NO_UPLOAD=1 stops after the archive and its checks.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
GEN="$HERE/Generated"
OUT="$ROOT/target/ios-testflight"
mkdir -p "$GEN" "$OUT"
export PATH="$HOME/.cargo/bin:/opt/homebrew/opt/rustup/bin:/usr/local/opt/rustup/bin:/opt/homebrew/bin:/usr/local/bin:$PATH"

die() { printf 'error: %s\n' "$*" >&2; exit 1; }
[ -n "${FILMCRAFT_TEAM:-}" ] || die "set FILMCRAFT_TEAM (your Apple Developer team id)"
[ -n "${FILMCRAFT_BUNDLE_ID:-}" ] || die "set FILMCRAFT_BUNDLE_ID (the identifier of the app in App Store Connect)"

AUTH=()
if [ -n "${ASC_KEY_PATH:-}" ]; then
  [ -n "${ASC_KEY_ID:-}" ] && [ -n "${ASC_ISSUER_ID:-}" ] || die "ASC_KEY_PATH also needs ASC_KEY_ID and ASC_ISSUER_ID"
  case "$(cd "$(dirname "$ASC_KEY_PATH")" && pwd)/" in
    "$ROOT"/*) die "keep the API key outside the repository" ;;
  esac
  AUTH=(-authenticationKeyPath "$ASC_KEY_PATH" -authenticationKeyID "$ASC_KEY_ID" -authenticationKeyIssuerID "$ASC_ISSUER_ID")
fi

{
  echo "// Generated by testflight.sh"
  echo "DEVELOPMENT_TEAM = $FILMCRAFT_TEAM"
  echo "PRODUCT_BUNDLE_IDENTIFIER = $FILMCRAFT_BUNDLE_ID"
  echo "CODE_SIGN_ENTITLEMENTS = FilmCraft/FilmCraft.entitlements"
} > "$GEN/Signing.xcconfig"

CONFIGURATION=Release PLATFORM_NAME=iphoneos "$HERE/build-rust.sh"
(cd "$HERE" && xcodegen generate --quiet)

# App Store Connect refuses a build number it has already seen
BUILD_NUMBER="$(date -u +%Y%m%d%H%M)"
ARCHIVE="$OUT/FilmCraft.xcarchive"
rm -rf "$ARCHIVE"
xcodebuild -project "$HERE/FilmCraft.xcodeproj" -scheme FilmCraft -configuration Release \
  -destination 'generic/platform=iOS' -archivePath "$ARCHIVE" -derivedDataPath "$OUT/DerivedData" \
  -allowProvisioningUpdates ${AUTH[@]+"${AUTH[@]}"} CURRENT_PROJECT_VERSION="$BUILD_NUMBER" \
  archive > "$OUT/archive.log" 2>&1 || { grep -E "error:" "$OUT/archive.log" | sort -u | head -20 >&2; die "the archive failed, see $OUT/archive.log"; }

"$HERE/check-private.sh" "$ARCHIVE/Products/Applications/FilmCraft.app"
[ "${FILMCRAFT_NO_UPLOAD:-0}" = 1 ] && { echo "Archive: $ARCHIVE (build $BUILD_NUMBER), not uploaded"; exit 0; }

cat > "$OUT/ExportOptions.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>method</key><string>app-store-connect</string>
	<key>destination</key><string>upload</string>
	<key>teamID</key><string>$FILMCRAFT_TEAM</string>
	<key>signingStyle</key><string>automatic</string>
	<key>testFlightInternalTestingOnly</key><false/>
</dict>
</plist>
PLIST
xcodebuild -exportArchive -archivePath "$ARCHIVE" -exportOptionsPlist "$OUT/ExportOptions.plist" \
  -exportPath "$OUT/export" -allowProvisioningUpdates ${AUTH[@]+"${AUTH[@]}"} > "$OUT/upload.log" 2>&1 \
  || { grep -E "error:" "$OUT/upload.log" | sort -u | head -20 >&2; die "the upload failed, see $OUT/upload.log"; }
echo "Build $BUILD_NUMBER uploaded: it appears in App Store Connect ▸ TestFlight once Apple has processed it."

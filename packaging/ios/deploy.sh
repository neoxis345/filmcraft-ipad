#!/bin/bash
# Build FilmCraft for iPadOS and install it on the connected iPad, in one command:
#
#   packaging/ios/deploy.sh
#
# Needs: Xcode (signed in with an Apple ID: Xcode ▸ Settings ▸ Accounts), Rust (rustup), and an iPad
# in Developer Mode, connected by cable or paired over the network. XcodeGen is fetched if missing.
#
# Optional settings (environment):
#   FILMCRAFT_TEAM=ABCDE12345           the signing team (default: the first "Apple Development" cert)
#   FILMCRAFT_BUNDLE_ID=com.you.filmcraft
#   FILMCRAFT_DEVICE=<udid or name>     which iPad (default: the first one available)
#   FILMCRAFT_NO_MEMORY_ENTITLEMENT=1   sign without the increased memory limit
#   FILMCRAFT_NO_INSTALL=1              build only
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
GEN="$HERE/Generated"
BUILD="$ROOT/target/ios-xcode"
mkdir -p "$GEN" "$BUILD"
export PATH="$HOME/.cargo/bin:/opt/homebrew/opt/rustup/bin:/usr/local/opt/rustup/bin:/opt/homebrew/bin:/usr/local/bin:$PATH"

say() { printf '\n\033[1;35m▸ %s\033[0m\n' "$*"; }
die() { printf '\n\033[1;31m✗ %s\033[0m\n' "$*" >&2; exit 1; }

# ---------------------------------------------------------------------------------------- tools
say "Outils"
command -v xcodebuild >/dev/null || die "Xcode est introuvable (xcode-select -p)."
xcodebuild -version | sed -n 1p
command -v rustup >/dev/null || die "Rust est introuvable : installez-le avec https://rustup.rs"
# (captured first: with pipefail, `grep -q` closing the pipe early would fail the whole line)
INSTALLED_TARGETS="$(rustup target list --installed 2>/dev/null || true)"
grep -qx 'aarch64-apple-ios' <<<"$INSTALLED_TARGETS" || rustup target add aarch64-apple-ios
rustc --version

XCODEGEN="$(command -v xcodegen || true)"
if [ -z "$XCODEGEN" ]; then
  if command -v brew >/dev/null; then
    brew install xcodegen >/dev/null && XCODEGEN="$(command -v xcodegen)"
  fi
fi
if [ -z "$XCODEGEN" ]; then
  # the release build from GitHub, kept next to the project
  T="$BUILD/xcodegen"
  if [ ! -x "$T/xcodegen/bin/xcodegen" ]; then
    mkdir -p "$T"
    curl -fsSL -o "$T/xcodegen.zip" https://github.com/yonaskolb/XcodeGen/releases/latest/download/xcodegen.zip
    unzip -qo "$T/xcodegen.zip" -d "$T"
  fi
  XCODEGEN="$T/xcodegen/bin/xcodegen"
fi
"$XCODEGEN" --version

# -------------------------------------------------------------------------------------- signing
say "Signature"
TEAM="${FILMCRAFT_TEAM:-}"
if [ -z "$TEAM" ]; then
  # the team (OU) of the first Apple Development certificate in the keychain
  CERTS="$(security find-certificate -a -c "Apple Development" -p 2>/dev/null || true)"
  TEAM="$(printf '%s\n' "$CERTS" \
    | awk '/BEGIN CERT/{c++} c==1' \
    | openssl x509 -noout -subject -nameopt multiline 2>/dev/null \
    | awk -F' = ' '/organizationalUnitName/{print $2}' | head -1 || true)"
fi
[ -n "$TEAM" ] || die "Aucune équipe de signature : ouvrez Xcode ▸ Réglages ▸ Comptes, ajoutez votre identifiant Apple, puis relancez (ou FILMCRAFT_TEAM=...)."
USER_ID="$(echo "${USER:-user}" | tr -cd '[:alnum:]' | tr '[:upper:]' '[:lower:]')"
BUNDLE="${FILMCRAFT_BUNDLE_ID:-com.$USER_ID.filmcraft}"
echo "équipe $TEAM · identifiant $BUNDLE"

write_signing() {
  {
    echo "// Generated by deploy.sh"
    echo "DEVELOPMENT_TEAM = $TEAM"
    echo "PRODUCT_BUNDLE_IDENTIFIER = $BUNDLE"
    if [ "${1:-with}" = with ]; then echo "CODE_SIGN_ENTITLEMENTS = FilmCraft/FilmCraft.entitlements"; fi
  } > "$GEN/Signing.xcconfig"
}
if [ "${FILMCRAFT_NO_MEMORY_ENTITLEMENT:-0}" = 1 ]; then write_signing without; else write_signing with; fi

# ------------------------------------------------------------------------------------------ iPad
# Found before building: Xcode adds the iPad to the signing profile only when it builds for it (a
# generic build makes a profile the iPad refuses: "This provisioning profile cannot be installed").
DEST='generic/platform=iOS'
if [ "${FILMCRAFT_NO_INSTALL:-0}" != 1 ]; then
  say "iPad"
  DEVICES="$BUILD/devices.json"
  xcrun devicectl list devices --json-output "$DEVICES" >/dev/null 2>&1 || true
  DEVICE="${FILMCRAFT_DEVICE:-}"
  if [ -z "$DEVICE" ]; then
    DEVICE="$(/usr/bin/python3 - "$DEVICES" <<'EOF'
import json, sys
try:
    devs = json.load(open(sys.argv[1]))["result"]["devices"]
except Exception:
    devs = []
def ok(d):
    hw = d.get("hardwareProperties", {})
    return hw.get("platform") == "iOS" and hw.get("deviceType") == "iPad" and d.get("connectionProperties", {}).get("tunnelState") != "unavailable"
for d in sorted(devs, key=lambda d: d.get("connectionProperties", {}).get("transportType") != "wired"):
    if ok(d):
        print(d.get("hardwareProperties", {}).get("udid") or d.get("identifier", "")); break
EOF
  )"
  fi
  [ -n "$DEVICE" ] || die "Aucun iPad trouvé : branchez-le, déverrouillez-le et faites-lui confiance, puis relancez."
  DEST="id=$DEVICE"
  echo "iPad $DEVICE"
fi

# ------------------------------------------------------------------------------------------- build
say "Moteur Rust (la première fois : 10 à 25 minutes)"
"$HERE/build-rust.sh"

say "Projet Xcode"
(cd "$HERE" && "$XCODEGEN" generate --quiet)

build() {
  xcodebuild -project "$HERE/FilmCraft.xcodeproj" -scheme FilmCraft -configuration Release \
    -destination "$DEST" -derivedDataPath "$BUILD/DerivedData" \
    -allowProvisioningUpdates -allowProvisioningDeviceRegistration \
    build 2>&1 | tee "$BUILD/xcodebuild.log" | grep -E "error:|warning: .*FilmCraft/|BUILD (SUCCEEDED|FAILED)|Signing Identity|Provisioning Profile" || true
  grep -q "BUILD SUCCEEDED" "$BUILD/xcodebuild.log"
}
say "Compilation et signature"
if ! build; then
  if grep -qiE "increased-memory-limit|entitlement|capabilit" "$BUILD/xcodebuild.log" && grep -q CODE_SIGN_ENTITLEMENTS "$GEN/Signing.xcconfig"; then
    echo "Ce compte ne permet pas la limite de mémoire augmentée : nouvel essai sans."
    write_signing without
    (cd "$HERE" && "$XCODEGEN" generate --quiet)
    build || die "La compilation a échoué : voir $BUILD/xcodebuild.log"
  else
    die "La compilation a échoué : voir $BUILD/xcodebuild.log"
  fi
fi
APP="$BUILD/DerivedData/Build/Products/Release-iphoneos/FilmCraft.app"
[ -d "$APP" ] || die "FilmCraft.app introuvable"
echo "app : $APP ($(du -sh "$APP" | cut -f1))"
[ "${FILMCRAFT_NO_INSTALL:-0}" = 1 ] && exit 0

# ----------------------------------------------------------------------------------------- install
say "Installation sur l'iPad"
xcrun devicectl device install app --device "$DEVICE" "$APP"
say "Lancement"
xcrun devicectl device process launch --device "$DEVICE" "$BUNDLE" || echo "Lancez FilmCraft depuis l'écran d'accueil de l'iPad."
say "FilmCraft est installé sur l'iPad."

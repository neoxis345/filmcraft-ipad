#!/bin/bash
# Build FilmCraft's Rust engine for iPadOS as a static library (apps/filmcraft-ios), and write the
# linker flags it needs to Generated/Rust.xcconfig. Xcode runs this before compiling the Swift
# sources; deploy.sh runs it first so the project is generated with the right flags.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
# the device, or the iPad simulator on this Mac (Xcode says which in PLATFORM_NAME)
TARGET="${FILMCRAFT_RUST_TARGET:-}"
if [ -z "$TARGET" ]; then
  case "${PLATFORM_NAME:-iphoneos}" in
    iphonesimulator) TARGET="aarch64-apple-ios-sim" ;;
    *) TARGET="aarch64-apple-ios" ;;
  esac
fi
GEN="$HERE/Generated"
mkdir -p "$GEN"

# Xcode runs scripts with its own environment: an iOS SDKROOT and compiler flags that would make
# the macOS build scripts of some crates (cc, build.rs) fail. Cargo gets a clean environment.
# rustup's own install puts cargo in ~/.cargo/bin; Homebrew's rustup in /opt/homebrew/opt/rustup/bin
RUST_PATH="$HOME/.cargo/bin:/opt/homebrew/opt/rustup/bin:/usr/local/opt/rustup/bin"
CARGO="${CARGO:-}"
if [ -z "$CARGO" ]; then CARGO="$(PATH="$RUST_PATH:$PATH" command -v cargo || true)"; fi
if [ -z "$CARGO" ]; then
  echo "error: cargo not found (install Rust with rustup: https://rustup.rs)" >&2
  exit 1
fi

LOG="$GEN/cargo.log"
cd "$ROOT"
PROFILE_FLAG="--release"
PROFILE="release"
if [ "${CONFIGURATION:-Release}" = "Debug" ]; then
  PROFILE_FLAG=""
  PROFILE="debug"
fi
# The binary embeds source paths (panic messages, debug info): a shipped app must not reveal this
# Mac's folders or user name, so they are rewritten to neutral ones.
RUSTFLAGS_PRIVATE="--remap-path-prefix=$ROOT=/filmcraft --remap-path-prefix=$HOME/.cargo=/cargo --remap-path-prefix=$HOME/.rustup=/rustup --remap-path-prefix=$HOME=/home"
env -i HOME="$HOME" USER="${USER:-}" TMPDIR="${TMPDIR:-/tmp}" LANG=en_US.UTF-8 \
  RUSTFLAGS="$RUSTFLAGS_PRIVATE" \
  PATH="$RUST_PATH:/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin" \
  IPHONEOS_DEPLOYMENT_TARGET=18.0 \
  "$CARGO" rustc $PROFILE_FLAG --target "$TARGET" -p filmcraft-ios --lib --crate-type staticlib \
  -- --print native-static-libs 2>&1 | tee "$LOG" | grep -E "^(error|warning: unused)|Compiling filmcraft|Finished|^note: native" || true

if grep -a -q "^error" "$LOG"; then
  echo "error: the Rust build failed, see $LOG" >&2
  grep -a -A12 "^error" "$LOG" | head -80 >&2
  exit 1
fi

LIB="$ROOT/target/$TARGET/$PROFILE/libfilmcraft_ios.a"
if [ ! -f "$LIB" ]; then
  echo "error: $LIB was not built" >&2
  exit 1
fi

# The system libraries and frameworks the Rust code links against, as rustc reports them (only
# printed when the library is linked again: kept from the last time otherwise).
NATIVE="$(grep -a -o 'native-static-libs: .*' "$LOG" | head -1 | sed 's/native-static-libs: //' || true)"
if [ -n "$NATIVE" ]; then echo "$NATIVE" > "$GEN/native-libs.txt"; fi
if [ ! -s "$GEN/native-libs.txt" ]; then
  echo "-framework Metal -framework QuartzCore -framework UIKit -framework Foundation -framework CoreFoundation -framework CoreGraphics -framework CoreMedia -framework CoreVideo -framework VideoToolbox -framework AudioToolbox -framework CoreAudio -framework AVFoundation -framework Security -framework IOSurface -lobjc -liconv -lSystem -lc -lm" > "$GEN/native-libs.txt"
fi
# Every SDK and configuration at once: Xcode reads this file before it runs this script, so a
# path written for the previous build (Debug, or the device) must never be the one linked.
T="$ROOT/target"
cat > "$GEN/Rust.xcconfig" <<EOF
// Generated by build-rust.sh: link the Rust engine (apps/filmcraft-ios).
FILMCRAFT_RUST_LIB[sdk=iphoneos*][config=Release] = $T/aarch64-apple-ios/release/libfilmcraft_ios.a
FILMCRAFT_RUST_LIB[sdk=iphoneos*][config=Debug] = $T/aarch64-apple-ios/debug/libfilmcraft_ios.a
FILMCRAFT_RUST_LIB[sdk=iphonesimulator*][config=Release] = $T/aarch64-apple-ios-sim/release/libfilmcraft_ios.a
FILMCRAFT_RUST_LIB[sdk=iphonesimulator*][config=Debug] = $T/aarch64-apple-ios-sim/debug/libfilmcraft_ios.a
OTHER_LDFLAGS = \$(inherited) \$(FILMCRAFT_RUST_LIB) $(cat "$GEN/native-libs.txt")
EOF
echo "Rust engine: $(du -h "$LIB" | cut -f1) $LIB"
